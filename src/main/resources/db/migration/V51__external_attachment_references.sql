-- References are not local files. Visibility is conservative until a bilateral
-- contract explicitly supplies a public-evidence classification.
CREATE TABLE external_attachment_references (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id UUID NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
    external_event_id UUID NOT NULL REFERENCES inbox_events(event_id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    ordinal INTEGER NOT NULL CHECK (ordinal >= 0),
    update_type VARCHAR(30) NOT NULL,
    source_module_id VARCHAR(20) NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL,
    file_name TEXT NOT NULL CHECK (length(btrim(file_name)) > 0),
    content_type TEXT NOT NULL CHECK (length(btrim(content_type)) > 0),
    url TEXT NOT NULL CHECK (length(btrim(url)) > 0),
    size_bytes BIGINT CHECK (size_bytes >= 0),
    visibility VARCHAR(20) NOT NULL CHECK (visibility IN ('PUBLIC','INTERNAL')),
    UNIQUE(external_event_id, ordinal)
);
CREATE INDEX idx_external_attachment_ticket ON external_attachment_references(ticket_id, occurred_at);
