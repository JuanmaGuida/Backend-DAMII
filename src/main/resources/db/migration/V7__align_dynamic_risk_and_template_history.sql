CREATE TABLE risk_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    form_field_id BIGINT NOT NULL,
    operator VARCHAR(30) NOT NULL,
    expected_value JSONB,
    value_from NUMERIC,
    value_to NUMERIC,
    risk_increment SMALLINT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_risk_rule_form_field
        FOREIGN KEY (form_field_id) REFERENCES form_fields (id),
    CONSTRAINT ck_risk_rule_operator CHECK (
        operator IN ('EQUALS', 'BETWEEN', 'GREATER_THAN', 'LESS_THAN', 'IN')
    ),
    CONSTRAINT ck_risk_rule_increment CHECK (
        risk_increment BETWEEN 0 AND 100
    ),
    CONSTRAINT ck_risk_rule_operands CHECK (
        (operator = 'EQUALS'
            AND expected_value IS NOT NULL
            AND expected_value <> 'null'::jsonb
            AND value_from IS NULL
            AND value_to IS NULL)
        OR
        (operator = 'IN'
            AND jsonb_typeof(expected_value) = 'array'
            AND value_from IS NULL
            AND value_to IS NULL)
        OR
        (operator = 'BETWEEN'
            AND expected_value IS NULL
            AND value_from IS NOT NULL
            AND value_to IS NOT NULL
            AND value_from <= value_to)
        OR
        (operator = 'GREATER_THAN'
            AND expected_value IS NULL
            AND value_from IS NOT NULL
            AND value_to IS NULL)
        OR
        (operator = 'LESS_THAN'
            AND expected_value IS NULL
            AND value_from IS NULL
            AND value_to IS NOT NULL)
    )
);

CREATE INDEX idx_risk_rule_form_field_active
    ON risk_rules (form_field_id, active);

