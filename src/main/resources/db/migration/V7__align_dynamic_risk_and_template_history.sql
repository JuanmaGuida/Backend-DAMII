DO $$
DECLARE
    actual_total BIGINT;
    actual_5 BIGINT;
    actual_10 BIGINT;
    actual_13 BIGINT;
    actual_18 BIGINT;
    actual_27 BIGINT;
    actual_36 BIGINT;
BEGIN
    SELECT
        COUNT(*),
        COUNT(*) FILTER (WHERE risk_increment = 5),
        COUNT(*) FILTER (WHERE risk_increment = 10),
        COUNT(*) FILTER (WHERE risk_increment = 13),
        COUNT(*) FILTER (WHERE risk_increment = 18),
        COUNT(*) FILTER (WHERE risk_increment = 27),
        COUNT(*) FILTER (WHERE risk_increment = 36)
    INTO actual_total, actual_5, actual_10, actual_13, actual_18, actual_27, actual_36
    FROM risk_rules;

    IF actual_total <> 303
        OR actual_5 <> 35
        OR actual_10 <> 39
        OR actual_13 <> 10
        OR actual_18 <> 54
        OR actual_27 <> 75
        OR actual_36 <> 90 THEN
        RAISE EXCEPTION
            'V7 abortada: se esperaban 303 RiskRule con distribución 5:35, 10:39, 13:10, 18:54, 27:75, 36:90; se obtuvieron total %, 5:%, 10:%, 13:%, 18:%, 27:%, 36:%',
            actual_total, actual_5, actual_10, actual_13, actual_18, actual_27, actual_36;
    END IF;
END $$;

UPDATE form_fields
SET config = config - 'riskScore'
WHERE config ? 'riskScore';

UPDATE form_fields ff
SET config = jsonb_set(ff.config, '{options}', cleaned.options, FALSE)
FROM (
    SELECT
        source.id,
        jsonb_agg(option_value - 'riskScore' ORDER BY option_order) AS options
    FROM form_fields source
    CROSS JOIN LATERAL jsonb_array_elements(
        CASE
            WHEN jsonb_typeof(source.config -> 'options') = 'array'
                THEN source.config -> 'options'
            ELSE '[]'::jsonb
        END
    ) WITH ORDINALITY AS option_entry(option_value, option_order)
    GROUP BY source.id
    HAVING BOOL_OR(option_value ? 'riskScore')
) cleaned
WHERE cleaned.id = ff.id;

