DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM tickets ticket
        JOIN (
            SELECT request_type_id, COUNT(*) AS template_count
            FROM form_templates
            GROUP BY request_type_id
        ) template_counts
          ON template_counts.request_type_id = ticket.request_type_id
        WHERE ticket.form_template_id IS NULL
          AND template_counts.template_count > 1
    ) THEN
        RAISE EXCEPTION
            'V7 no puede inferir form_template_id: existen tickets históricos para RequestType con múltiples FormTemplate';
    END IF;
END $$;

UPDATE tickets ticket
SET form_template_id = single_template.form_template_id
FROM (
    SELECT request_type_id, MIN(id) AS form_template_id
    FROM form_templates
    GROUP BY request_type_id
    HAVING COUNT(*) = 1
) single_template
WHERE ticket.request_type_id = single_template.request_type_id
  AND ticket.form_template_id IS NULL;

